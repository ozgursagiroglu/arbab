// The marker of a generated lane (verify, reviewer, skeptic): <runs>/<lane>/generated.json names the integration that
// generated it and the integration head it started from. Only that integration's commands may reset or launch it;
// `arbab launch` and `arbab resume` refuse it, so a hand-launched lane is never mistaken for a generated one.
import { existsSync } from "node:fs";
import { join } from "node:path";
import { listLanes } from "../registry";
import { ArbabError } from "../util/errors";
import { readJson, writeJsonAtomic } from "../util/fs";
import { assertValidName } from "../util/names";

/** Which integration generated a lane; written into the lane's run dir before its first launch. */
export interface GenerationOwner {
  /** The integration name. */
  integration: string;
  /** Its branch, integrate/<name>. */
  branch: string;
  /** The integration head the lane works on (installed on a trusted commit, then fast-forwarded there). */
  head: string;
}

export interface GeneratedMarker {
  /** `integration:<name>` */
  by: string;
  createdAt: string;
  /**
   * The integration head the lane works on, where its branch ends until a worker commits; absent in markers written
   * before it was recorded.
   */
  baseSha?: string;
}

const GENERATED = "generated.json";
const BY = "integration:";
const SHA = /^[0-9a-f]{40,64}$/;

export const ownerTag = (owner: Pick<GenerationOwner, "integration">): string => `${BY}${owner.integration}`;

const markerPath = (runsRoot: string, lane: string): string => join(runsRoot, assertValidName(lane, "lane"), GENERATED);

/** Records that `owner` generated `lane` from `owner.head`, so a later run of the same command may reset it. */
export function markGenerated(runsRoot: string, lane: string, owner: GenerationOwner, now: string): void {
  const marker: GeneratedMarker = { by: ownerTag(owner), createdAt: now, baseSha: owner.head };
  writeJsonAtomic(markerPath(runsRoot, lane), marker);
}

/** The lane's marker with its fields checked, or null when the lane has none. A field that does not fit is dropped. */
export function readGenerated(runsRoot: string, lane: string): { by: string | null; baseSha: string | null } | null {
  const path = markerPath(runsRoot, lane);
  if (!existsSync(path)) return null;
  let raw: unknown;
  try {
    raw = readJson<unknown>(path);
  } catch {
    // A damaged marker still says the lane was generated.
    raw = null;
  }
  const fields = typeof raw === "object" && raw !== null && !Array.isArray(raw) ? (raw as Record<string, unknown>) : {};
  return {
    by: typeof fields["by"] === "string" ? fields["by"] : null,
    baseSha: typeof fields["baseSha"] === "string" && SHA.test(fields["baseSha"]) ? fields["baseSha"] : null,
  };
}

/** The lanes whose marker names `integration` as their generator, by name. */
export function lanesGeneratedBy(runsRoot: string, integration: string): string[] {
  const tag = ownerTag({ integration });
  return listLanes(runsRoot).filter((lane) => readGenerated(runsRoot, lane)?.by === tag);
}

/** Refuses a lane an integration generated: only that integration's verify or review may run it. */
export function assertNotGenerated(runsRoot: string, lane: string): void {
  const marker = readGenerated(runsRoot, lane);
  if (marker === null) return;
  const owner = marker.by?.startsWith(BY) === true ? marker.by.slice(BY.length) : null;
  throw new ArbabError(
    "usage",
    `lane ${lane} was generated by ${owner === null ? "an integration" : `integration ${owner}`}, which owns the name; ` +
      "only its arbab verify or arbab review runs it. Give your lane another name",
  );
}
