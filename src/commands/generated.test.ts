import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { afterEach, beforeEach, describe, expect, it } from "vitest";
import { assertNotGenerated, lanesGeneratedBy, markGenerated, ownerTag, readGenerated } from "./generated";

let runsRoot: string;
beforeEach(() => {
  runsRoot = mkdtempSync(join(tmpdir(), "arbab-"));
});
afterEach(() => rmSync(runsRoot, { recursive: true, force: true }));

const HEAD = "a".repeat(40);
const T = "2026-10-09T12:00:00.000Z";
const writeMarker = (lane: string, text: string): void => {
  mkdirSync(join(runsRoot, lane), { recursive: true });
  writeFileSync(join(runsRoot, lane, "generated.json"), text);
};

describe("markGenerated and readGenerated", () => {
  it("records the owner and the head the lane starts from, and reads them back", () => {
    markGenerated(runsRoot, "rel-verify", { integration: "rel", branch: "integrate/rel", head: HEAD }, T);
    expect(JSON.parse(readFileSync(join(runsRoot, "rel-verify", "generated.json"), "utf8"))).toEqual({ by: "integration:rel", createdAt: T, baseSha: HEAD });
    expect(readGenerated(runsRoot, "rel-verify")).toEqual({ by: ownerTag({ integration: "rel" }), baseSha: HEAD });
  });

  it("is null without a marker, and drops fields that do not fit", () => {
    expect(readGenerated(runsRoot, "none")).toBeNull();
    writeMarker("old", JSON.stringify({ by: "integration:rel", createdAt: T }));
    expect(readGenerated(runsRoot, "old")).toEqual({ by: "integration:rel", baseSha: null });
    writeMarker("odd", JSON.stringify({ by: 3, baseSha: "HEAD" }));
    expect(readGenerated(runsRoot, "odd")).toEqual({ by: null, baseSha: null });
    writeMarker("torn", "{");
    expect(readGenerated(runsRoot, "torn")).toEqual({ by: null, baseSha: null });
  });

  it("refuses a lane name that is not valid", () => {
    expect(() => markGenerated(runsRoot, "../x", { integration: "rel", branch: "integrate/rel", head: HEAD }, T)).toThrow(/lane/);
    expect(() => readGenerated(runsRoot, "../x")).toThrow(/lane/);
  });
});

describe("lanesGeneratedBy", () => {
  it("lists the lanes whose marker names the integration, and none of another's, a damaged marker's or a hand lane's", () => {
    markGenerated(runsRoot, "rel-verify", { integration: "rel", branch: "integrate/rel", head: HEAD }, T);
    markGenerated(runsRoot, "rel-review-security", { integration: "rel", branch: "integrate/rel", head: HEAD }, T);
    markGenerated(runsRoot, "relx-verify", { integration: "relx", branch: "integrate/relx", head: HEAD }, T);
    writeMarker("torn", "{");
    mkdirSync(join(runsRoot, "demo"));
    expect(lanesGeneratedBy(runsRoot, "rel")).toEqual(["rel-review-security", "rel-verify"]);
    expect(lanesGeneratedBy(runsRoot, "other")).toEqual([]);
  });

  it("is empty without a runs directory", () => {
    expect(lanesGeneratedBy(join(runsRoot, "none"), "rel")).toEqual([]);
  });
});

describe("assertNotGenerated", () => {
  it("passes a lane without a marker", () => {
    expect(() => assertNotGenerated(runsRoot, "demo")).not.toThrow();
  });

  it("refuses a generated lane, naming the integration that owns it", () => {
    markGenerated(runsRoot, "rel-verify", { integration: "rel", branch: "integrate/rel", head: HEAD }, T);
    expect(() => assertNotGenerated(runsRoot, "rel-verify")).toThrow(
      expect.objectContaining({ code: "usage", message: expect.stringMatching(/^lane rel-verify was generated by integration rel, which owns the name/) }),
    );
  });

  it("refuses a lane whose marker is damaged too", () => {
    writeMarker("torn", "{");
    expect(() => assertNotGenerated(runsRoot, "torn")).toThrow(/generated by an integration/);
  });
});
