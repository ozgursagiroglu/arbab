/** What a character the font lacks draws: a hollow box as wide as "0". */
const MISSING: readonly string[] = ["#####", "#...#", "#...#", "#...#", "#...#", "#...#", "#####"];

interface Run {
  x: number;
  y: number;
  w: number;
}

interface Glyph {
  w: number;
  runs: readonly Run[];
}

/** Grid → runs, one per stretch of adjacent pixels in a row. A malformed grid is a bug in the art and throws. */
function compile(ch: string, grid: readonly string[]): Glyph {
  if (grid.length !== ASCENT && grid.length !== ASCENT + DESCENT) {
    throw new Error(`glyph ${JSON.stringify(ch)} has ${grid.length} rows`);
  }
  const w = grid[0]?.length ?? 0;
  const runs: Run[] = [];
  grid.forEach((row, y) => {
    if (row.length !== w || !/^[#.]*$/.test(row)) throw new Error(`glyph ${JSON.stringify(ch)} row ${y} is malformed`);
    for (let x = 0; x < w; x++) {
      if (row[x] !== "#") continue;
      let end = x + 1;
      while (row[end] === "#") end++;
      runs.push({ x, y, w: end - x });
      x = end;
    }
  });
  return { w, runs };
}

const COMPILED: ReadonlyMap<string, Glyph> = new Map(Object.entries(GLYPHS).map(([ch, grid]) => [ch, compile(ch, grid)]));
const MISSING_GLYPH = compile("missing", MISSING);

function glyphOf(ch: string): Glyph {
  return COMPILED.get(ch) ?? MISSING_GLYPH;
}

/** Width in font pixels of `text` drawn at scale 1, letter spacing included (no trailing space). */
export function measureText(text: string): number {
  let width = 0;
  let count = 0;
  for (const ch of text) {
    width += glyphOf(ch).w;
    count++;
  }
  return count === 0 ? 0 : width + (count - 1) * TRACKING;
}

/**
 * Draws `text` with the top of its ascent at (x, y), each font pixel a `scale` × `scale` square of `color`, and
 * returns the width drawn in px. Characters the font lacks draw as a hollow box of the same width as "0".
 */
export function drawText(ctx: Canvas2D, text: string, x: number, y: number, color: string, scale = 1): number {
  if (!Number.isFinite(scale) || scale <= 0) return 0;
  ctx.fillStyle = color;
  let cursor = 0;
  let first = true;
  // Code points, not UTF-16 units: an emoji is one missing glyph, not two.
  for (const ch of text) {
    if (!first) cursor += TRACKING;
    first = false;
    const glyph = glyphOf(ch);
    for (const run of glyph.runs) {
      ctx.fillRect(x + (cursor + run.x) * scale, y + run.y * scale, run.w * scale, scale);
    }
    cursor += glyph.w;
  }
  return cursor * scale;
}
